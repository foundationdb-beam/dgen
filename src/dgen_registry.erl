%% ---------------------------------------------------------------------------
%% OTP via-tuple registry contract
%% ---------------------------------------------------------------------------

-if(?DOCATTRS).
-doc """
Registers `Pid` under `{RegistryName, LogicalName}`.

Routes through the local member, which forwards to the leader if needed.
Returns `yes` on success, `no` if the name is already taken or no leader
is currently elected.
""".
-endif.
-spec register_name({atom(), term()}, pid()) -> yes | no.
register_name(Name, Pid) ->
    register_name(Name, Pid, #{}).

-if(?DOCATTRS).
-doc """
Removes the registration for `{RegistryName, LogicalName}`.

Fire-and-forget: routes through the local member, which forwards to the
leader. The local member also removes the entry from its own map
immediately so snapshot reads on this node are consistent right away.
""".
-endif.
-spec unregister_name({atom(), term()}) -> ok.
unregister_name({RegistryName, LogicalName}) ->
    gen_server:cast(member_name(RegistryName), {unregister, LogicalName}).

-if(?DOCATTRS).
-doc """
Snapshot read — served lock-free from the local member's ETS table.

Runs entirely in the **calling process** (an `ets:lookup/2` against the member's
`protected` names table), so it never blocks on the member's mailbox, the leader,
or the backend — many callers read concurrently. May be slightly stale on follower
nodes in the brief window between a remote registration and the replication cast
arriving, and returns `undefined` while the member is (re)starting and its table
does not yet exist.
""".
-endif.
-spec whereis_name({atom(), term()}) -> pid() | undefined.
whereis_name({RegistryName, LogicalName}) ->
    try ets:lookup(names_table(RegistryName), LogicalName) of
        [{_Name, Pid, _Index, _Data} | _] -> Pid;
        [] -> undefined
    catch
        %% The table does not exist yet (member starting / restarting after a
        %% crash) — treat as not-registered rather than crashing the caller.
        error:badarg -> undefined
    end.

-if(?DOCATTRS).
-doc """
Sends `Msg` to the process registered as `Name`, returning the Pid.

Exits with reason `{badarg, {Name, Msg}}` if the name is not registered.
Called internally by gen_server/gen_event for `{via, …}` routing.
""".
-endif.
-spec send({atom(), term()}, term()) -> pid().
send(Name, Msg) ->
    case whereis_name(Name) of
        undefined ->
            exit({badarg, {Name, Msg}});
        Pid ->
            Pid ! Msg,
            Pid
    end.

%% ---------------------------------------------------------------------------
%% Registration metadata
%% ---------------------------------------------------------------------------
%% Metadata is attached to a registration (keyed by name) and lives exactly as long as
%% the registration does — it is removed automatically when the process exits or is
%% unregistered. A `MetaSpec` is `#{index => #{attr() => value()}, data => term()}`
%% (both optional): `index` is the queryable metadata, `data` an opaque payload returned
%% verbatim. See §4.7 of the design doc.

-if(?DOCATTRS).
-doc """
Registers `Pid` under `{RegistryName, LogicalName}` with metadata, in one fenced step.

`MetaSpec` is `#{index => map(), data => term()}` (both optional; defaults `#{}` and
`undefined`). Like `register_name/2`, returns `yes` on success or `no` if the name is
already taken, no leader is currently elected, or the leader could not be reached in
time — registration always returns a verdict rather than exiting on a routing
timeout (a caller that hears `no` retries; it never has to handle a timeout exit).
""".
-endif.
-spec register_name({atom(), term()}, pid(), map()) -> yes | no.
register_name({RegistryName, LogicalName}, Pid, MetaSpec) ->
    try
        gen_server:call(member_name(RegistryName), {register, LogicalName, Pid, meta_of(MetaSpec)})
    catch
        %% The member (or the leader behind it) did not answer in time — e.g. the
        %% leader became unreachable after the forward was sent.  The contract is a
        %% verdict, not an exit: answer `no` so the caller retries.  A missing
        %% registry (noproc) still exits — that is a usage error, not a timeout.
        exit:{timeout, _} -> no
    end.

-if(?DOCATTRS).
-doc """
Replaces the metadata of the existing registration `{RegistryName, LogicalName}`.

`MetaSpec` is `#{index => map(), data => term()}` (both optional; an omitted field
becomes `#{}` / `undefined` — this is a replace, not a merge). Routes through the leader
and rides the fenced commit. Returns `ok`, `{error, not_registered}` if the name is not
currently bound, or `{error, no_leader}` if no leader is elected (or leadership changed
mid-flight — retry).
""".
-endif.
-spec set_metadata({atom(), term()}, map()) -> ok | {error, not_registered | no_leader}.
set_metadata({RegistryName, LogicalName}, MetaSpec) ->
    {Index, Data} = meta_of(MetaSpec),
    try
        gen_server:call(member_name(RegistryName), {set_metadata, LogicalName, Index, Data})
    catch
        exit:_ -> {error, no_leader}
    end.

-if(?DOCATTRS).
-doc """
Snapshot read of a registration's metadata — served lock-free from the calling process.

Like `whereis_name/1`, this is an `ets:lookup/2` against the local member's `protected`
table with no member round-trip. Returns `{ok, #{pid := pid(), index := map(), data :=
term()}}` for a registered name, or `undefined` if it is not registered (or the member's
table does not exist yet). May lag a recent change made on another node.
""".
-endif.
-spec get_metadata({atom(), term()}) ->
    {ok, #{pid := pid(), index := map(), data := term()}} | undefined.
get_metadata({RegistryName, LogicalName}) ->
    try ets:lookup(names_table(RegistryName), LogicalName) of
        [{_Name, Pid, Index, Data} | _] -> {ok, #{pid => Pid, index => Index, data => Data}};
        [] -> undefined
    catch
        error:badarg -> undefined
    end.

-if(?DOCATTRS).
-doc """
Consistent metadata read routed through the leader (authoritative, never stale).

Returns the same shape as `get_metadata/1`. More expensive (one network hop) but
reflects the leader's committed view.
""".
-endif.
-spec get_metadata_consistent({atom(), term()}) ->
    {ok, #{pid := pid(), index := map(), data := term()}} | undefined.
get_metadata_consistent({RegistryName, LogicalName}) ->
    try
        gen_server:call(member_name(RegistryName), {get_metadata, LogicalName})
    catch
        exit:_ -> undefined
    end.

-if(?DOCATTRS).
-doc """
Finds every registration whose indexed metadata satisfies *all* of `Constraints`.

`Constraints` is `#{attr() => value()}` — a conjunction of exact equalities (AND-equal)
matched against each registration's `index` map. Returns a point-in-time list of
`#{name, pid, index, data}` matches (possibly empty), or `{error, empty_query}` if
`Constraints` is empty (use a future `list/1` for "everything").

This is a **batch-consistent snapshot** read of the local member's replica: it runs on
the member's mailbox (unlike the lock-free single-key reads) so it never observes a
half-applied group commit, but it may still lag a change made on another node. A
returned pid may already have died — treat results as candidates, not liveness
guarantees.
""".
-endif.
-spec query(atom(), map()) ->
    [#{name := term(), pid := pid(), index := map(), data := term()}] | {error, empty_query}.
query(_RegistryName, Constraints) when map_size(Constraints) =:= 0 ->
    {error, empty_query};
query(RegistryName, Constraints) ->
    try
        gen_server:call(member_name(RegistryName), {query, Constraints})
    catch
        exit:_ -> []
    end.

-if(?DOCATTRS).
-doc """
Like `query/2`, but routed through the leader for an authoritative (never-stale) result.

Returns the same shape as `query/2`. More expensive (it serialises on the leader's
mailbox, one network hop from a follower) but reflects the leader's committed view.
""".
-endif.
-spec query_consistent(atom(), map()) ->
    [#{name := term(), pid := pid(), index := map(), data := term()}] | {error, empty_query}.
query_consistent(_RegistryName, Constraints) when map_size(Constraints) =:= 0 ->
    {error, empty_query};
query_consistent(RegistryName, Constraints) ->
    try
        gen_server:call(member_name(RegistryName), {query_consistent, Constraints})
    catch
        exit:_ -> []
    end.

%% Parse a public MetaSpec (`#{index => …, data => …}`, both optional) into the internal
%% `{Index, Data}` pair, defaulting to the empty metadata.
-spec meta_of(map()) -> {map(), term()}.
meta_of(MetaSpec) ->
    {maps:get(index, MetaSpec, #{}), maps:get(data, MetaSpec, undefined)}.


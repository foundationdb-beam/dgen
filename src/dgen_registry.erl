        dgen_server:priority_call(Pid, get_subscriptions)
    end).

%% Route a durable subscription write to the elector as a fire-and-forget cast (handled
%% by dgen_registry_elector:handle_cast_tx/3 — enqueued durably and committed in the
%% consume transaction).  A missing registry is a usage error and exits, mirroring the
%% register path; a cast to a live elector that then dies is a harmless no-op.
elector_cast(RegistryName, Msg) ->
    case elector_pid(RegistryName) of
        undefined -> exit({noproc, {?MODULE, elector, RegistryName}});
        Pid -> dgen_server:cast(Pid, Msg)
    end.

%% ---------------------------------------------------------------------------
%% Teardown / durable-state cleanup
%% ---------------------------------------------------------------------------

-if(?DOCATTRS).
-doc """
Removes **all** of the registry's durable backend state. Returns `ok`.

Every key a registry writes — the elector's membership/leader/subscription state and its
message queue, plus the leader-fence and version keys — lives under a single tenant
keyspace prefix derived from `Name`, so this clears exactly that registry's keys (and no
other registry sharing the tenant). Use it to reclaim the durable footprint of a
registry you are done with — e.g. one of many short-lived, per-entity registries in a
shared tenant (see the "Process identity" note on why nothing else is left behind).

**Stop the registry first.** `delete/2` operates directly on the backend and assumes no
live processes: a running elector caches its state in memory and would re-write it (and
so re-create the keys) on its next commit. The correct sequence is
`Supervisor.stop(Sup)` (the pid `start_link/2,3` returned), then `delete/2` with the
tenant you started the registry with.

This does not delete anything the registered processes themselves own; it only removes
the registry's own bookkeeping.
""".
-endif.
-spec delete(atom(), dgen_backend:tenant()) -> ok.
delete(Name, Tenant) ->
    Tuid = dgen_registry_elector:tuid(Name),
    Backend = dgen_config:backend(),
    dgen_backend:transactional(Tenant, fun({Tx, Dir}) ->
        {StartKey, EndKey} = Backend:dir_range(Dir, Tuid),
        Backend:clear_range(Tx, StartKey, EndKey)
    end),
    ok.

%% Normalise a public query into the internal tagged form: a bare constraints map is
%% read as `{all, Map}` (AND-equal); an already-tagged query passes through.
-spec normalize_query(query()) -> {'all', map()}.

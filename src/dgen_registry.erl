%% Presence: durable watch/notify subscriptions
%% ---------------------------------------------------------------------------

-if(?DOCATTRS).
-doc """
Creates (or updates) a **durable** presence subscription `SubId`: keeps the processes
matching the `Notify` query up to date with the set of processes matching the `Watch`
query.

`Watch` and `Notify` are `query/0` values — a `{all, #{attr => value}}` conjunction of
exact equalities over registration `index` metadata (a bare map is accepted and read as
`{all, Map}`). `SubId` is any application term; a subscribe with an existing `SubId` is
an idempotent **upsert** (replaces its queries).

Whenever a committed batch of registrations changes which processes satisfy `Watch` — a
process registers into it, unregisters/dies out of it, or a metadata change moves it in
or out — the registry sends, to **every process currently matching `Notify`**, one
message:

```erlang
{dgen_presence, SubId, Events}
```

where `Events` is a non-empty list of `presence_event/0` — `{joined, Name, Pid}` /
`{left, Name, Pid}`. Every process that matches `Notify` receives an **initial snapshot**
(the current `Watch` set as a batch of `joined` events) when it enters the notify set —
whether that is at subscribe time or when it registers into `Notify` later — and deltas
thereafter. A viewer therefore always has a complete, continuously-maintained view from
the moment it appears, so the subscription can safely be created before any viewer exists
(e.g. tied to a database entity's lifetime).

## Durability

The subscription is stored in the elector's **durable** backend state, not tied to any
Erlang process: it outlives the cluster. An application can therefore tie a
subscription's lifetime to a database entity (subscribe when the entity is created,
`unsubscribe/2` when it is deleted) and have presence come back intact after a
scale-to-zero — the durable subscription is reloaded and re-fed to the leader on
restart, and processes matching `Notify` resume receiving updates as they re-register.

Returns `ok`, or `{error, empty_query}` if either query is empty (validated locally).
The write is sent to the elector as a durable **cast** (fire-and-forget) for low latency,
so `ok` means "accepted for durable processing", not "already committed": it commits
asynchronously and `subscriptions/1` reflects it shortly after. Durability still holds —
the change commits in the elector's backend transaction and survives a full cluster
restart — and because a subscription is an idempotent upsert keyed by `SubId`, a write
lost in the narrow window before the elector durably enqueues it is safely recoverable by
re-subscribing (the application owns the source of truth). A missing registry (`noproc`)
exits.
""".
-endif.
-spec subscribe(atom(), term(), query(), query()) -> ok | {error, empty_query}.
subscribe(RegistryName, SubId, Watch, Notify) ->
    {all, W} = NWatch = normalize_query(Watch),
    {all, N} = NNotify = normalize_query(Notify),
    case map_size(W) =:= 0 orelse map_size(N) =:= 0 of
        true ->
            {error, empty_query};
        false ->
            elector_cast(RegistryName, {subscribe, SubId, NWatch, NNotify})
    end.


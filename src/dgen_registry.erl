-if(?DOCATTRS).
-doc """
Registers `Pid` under `{RegistryName, LogicalName}`.

Routes through the local member, which forwards to the leader if needed.
Returns `yes` on success, `no` if the name is already held by a *different*
process or no leader is currently elected.

Registering the **same** pid under the **same** name again is an idempotent
`yes` (not a `no`): a caller whose register call timed out — but whose
registration in fact committed — can safely redrive it and get a decisive
`yes` for its own binding. See `register_name/3` for the timeout contract.
""".
-endif.
-spec register_name({atom(), term()}, pid()) -> yes | no.
register_name(Name, Pid) ->
    register_name(Name, Pid, #{}).

-if(?DOCATTRS).
-doc """
Removes the registration for `{RegistryName, LogicalName}`. Always returns `ok`.

Routes through the local member as a **call** (mirroring the register path): the
member removes the entry from its own replica immediately — snapshot reads on this
node see the delete at once — and forwards the removal to the leader as a *tracked*
request. `ok` normally means the leader has committed the removal; if the leader is
unreachable (or answers late), `ok` means the removal is **stashed and re-driven** —
forwarded to the current leader as a pid-guarded retract on the next leadership
change or rejoin snapshot — so an explicit unregister is never silently lost
(Non-goal 5 of the design doc). Cluster-wide visibility remains eventually
consistent (replication is asynchronous).
""".
-endif.
-spec unregister_name({atom(), term()}) -> ok.
unregister_name({RegistryName, LogicalName}) ->
    try
        gen_statem:call(
            member_name(RegistryName),
            {unregister, LogicalName},
            %% Same caller-side bound as the other leader-routed writes — see
            %% set_metadata/2.
            dgen_config:register_timeout(#{})
        )
    catch
        %% noproc: the registry is stopped/absent — nothing to unregister, `ok` is
        %% truthful.  timeout: the removal is already stashed on the member and will
        %% be re-driven; the public contract stays `ok` (the via machinery ignores
        %% the return value, and unlike register there is no wrong verdict to mask).
        exit:_ -> ok
    end.

-if(?DOCATTRS).
-doc """
Snapshot read — served lock-free from the local member's ETS table.

Runs entirely in the **calling process** (an `ets:lookup/2` against the member's
`protected` names table), so it never blocks on the member's mailbox, the leader,
or the backend — many callers read concurrently. May be slightly stale on follower
nodes in the brief window between a remote registration and the replication cast
arriving, and returns `undefined` while the member is (re)starting and its table
does not yet exist.
""".
-endif.
-spec whereis_name({atom(), term()}) -> pid() | undefined.
whereis_name({RegistryName, LogicalName}) ->
    try ets:lookup(names_table(RegistryName), LogicalName) of
        [{_Name, Pid, _Index, _Data} | _] -> Pid;
        [] -> undefined
    catch
        %% The table does not exist yet (member starting / restarting after a
        %% crash) — treat as not-registered rather than crashing the caller.
        error:badarg -> undefined
    end.

-if(?DOCATTRS).
-doc """
Sends `Msg` to the process registered as `Name`, returning the Pid.

Exits with reason `{badarg, {Name, Msg}}` if the name is not registered.
Called internally by gen_server/gen_event for `{via, …}` routing.
""".
-endif.
-spec send({atom(), term()}, term()) -> pid().
send(Name, Msg) ->
    case whereis_name(Name) of
        undefined ->
            exit({badarg, {Name, Msg}});
        Pid ->
            Pid ! Msg,
            Pid
    end.


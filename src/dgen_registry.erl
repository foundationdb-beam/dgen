""".
-endif.
-spec member_name(atom()) -> atom().
member_name(Name) ->
    Name.

-if(?DOCATTRS).
-doc """
Returns the ETS table name holding the registry's local `Name => Pid` replica.

Identity today (`names_table(Name) =:= Name`) — the member's names table is
named `Name` directly (ETS `named_table` names and Erlang process-registration
names are separate namespaces, so this does not collide with the member's own
registration). The table is owned and written by the member (a `protected`,
`read_concurrency` table) and read lock-free from any process — see
`whereis_name/1`.
""".
-endif.
-spec names_table(atom()) -> atom().
names_table(Name) ->
    Name.

-if(?DOCATTRS).
-doc """
Returns the current elector `pid()` for registry `Name`, or `undefined` if the
member (and so the elector) cannot currently be found.

The elector has no registered name — it is discovered by locating the member
(registered as `Name`), reading its `$ancestors` process-dictionary entry (set by
`proc_lib` at spawn time) to find the shared supervisor, then reading that
supervisor's children (`supervisor:which_children/1`) for the one with child id
`elector`. This is an all-local, in-memory operation (no network hop); it is what
`get_leader/1`, `get_epoch/1`, and `get_members/1` use internally, and is exported
for introspection.
""".
-endif.
-spec elector_pid(atom()) -> pid() | undefined.
elector_pid(Name) ->
    case whereis(Name) of
        undefined ->
            undefined;
        MemberPid ->
            case ancestors_of(MemberPid) of
                [Sup | _] ->
                    case lists:keyfind(elector, 1, supervisor:which_children(Sup)) of
                        {elector, ElectorPid, _Type, _Modules} when is_pid(ElectorPid) ->
                            ElectorPid;
                        _ ->
                            undefined
                    end;
                [] ->
                    undefined
            end
    end.

%% Reads Pid's `$ancestors` process-dictionary entry: the list of supervisor/starter
%% identifiers `proc_lib` records for a process at spawn time, immediate parent
%% first. There is no public `proc_lib` accessor for this (it is conventionally read
%% straight out of the dictionary — the same technique tools like `recon` use); each
%% entry is a pid, or a registered name if that ancestor had one, either of which
%% `supervisor:which_children/1` accepts directly.
-spec ancestors_of(pid()) -> [pid() | atom()].
ancestors_of(Pid) ->
    case erlang:process_info(Pid, dictionary) of
        {dictionary, Dict} -> proplists:get_value('$ancestors', Dict, []);
        undefined -> []
    end.

%% ---------------------------------------------------------------------------
%% Supervisor callbacks
%% ---------------------------------------------------------------------------

init({Name, Tenant, Opts}) ->
    %% Elector must start first: the member discovers it (via this supervisor,
    %% see dgen_registry_member's `discover_elector` handle_continue) and casts
    %% `{join, MemberId}` to it right after. A large consume_k is chosen because the
    %% in-transaction work is very small, and we want to keep a single node as the
    %% sole consumer as much as possible, to avoid leadership churn. consume_k > 1
    %% also disables dgen_server inlining, so every elector call rides the batched
    %% consume loop rather than being served ad hoc on the receiving node — keeping
    %% the consumer (hence the leader) stable.
    %%
    %% The elector is deliberately unnamed (`dgen_server:start_link/3`, no `Reg`):
    %% it has no registered name at all, local or otherwise. The member finds it by
    %% pid via this supervisor instead — see the "Process identity" moduledoc note.
    ElectorSpec = #{
        id => elector,
        start =>
            {dgen_server, start_link, [
                dgen_registry_elector,
                #{name => Name},
                [{tenant, Tenant}, {consume_k, 50}]
            ]},
        restart => permanent,
        shutdown => 5000,
        type => worker,
        modules => [dgen_server, dgen_registry_elector]
    },

    %% Tuid matches the elector's (see dgen_registry_elector:init/1) so the member
    %% can compute the leader key and the per-registry version key directly.
    Tuid = {<<"dgen_registry.">>, atom_to_binary(Name)},
    MemberSpec = #{
        id => member,
        start =>
            {dgen_registry_member, start_link, [
                Name,
                #{
                    name => Name,
                    tenant => Tenant,
                    tuid => Tuid,
                    config => Opts
                }
            ]},
        restart => permanent,
        shutdown => 5000,
        type => worker,
        modules => [dgen_registry_member]
    },

    %% one_for_all: the elector and member are one unit (the member holds a pid
    %% reference to the elector, discovered once at startup — see the moduledoc's
    %% "Process identity" note). If either crashes, restart both together so the
    %% member never runs with a stale elector reference; there is no cross-restart
    %% pid-staleness case to handle at the application level.
    {ok, {#{strategy => one_for_all, intensity => 5, period => 10}, [ElectorSpec, MemberSpec]}}.

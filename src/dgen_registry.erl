-module(dgen_registry).
-behaviour(supervisor).

-define(DOCATTRS, ?OTP_RELEASE >= 27).

-if(?DOCATTRS).
-moduledoc """
OTP-compatible process registry implementing the `{via, dgen_registry, {RegistryName, LogicalName}}` contract.

Standard OTP processes (`gen_server`, `gen_statem`, `gen_event`, etc.) can be registered
and addressed by name across an Erlang cluster.

See `docs/dgen_registry_design.md` for the full design, guarantees, and non-goals;
section references (e.g. `§5.7`) in the registry modules point there.

This module implements the four-function contract required for OTP `via` tuples:

- `register_name/2` — consistent write through the leader
- `unregister_name/1` — consistent delete through the leader
- `whereis_name/1` — lock-free snapshot read from the local member's ETS table
- `send/2` — routes a message to a named process

## Name terms

Every `via` name is a two-tuple `{RegistryName, LogicalName}` where
`RegistryName` identifies which registry to use (the one started with
`start_link/2`), and `LogicalName` is any term meaningful to the
application (atom, binary, tuple, …).

## Example

```erlang
{ok, _} = dgen_registry:start_link(my_registry, Tenant),

%% Start a gen_server registered in the dgen registry
gen_server:start_link({via, dgen_registry, {my_registry, user_service}},
                      my_server, [], []),

%% Call it from anywhere on the cluster
gen_server:call({via, dgen_registry, {my_registry, user_service}}, ping).
```

## Process identity

Starting a registry creates zero atoms. `Name` is supplied by the caller and is
application-controlled, not generated by this module. The top-level supervisor and
the elector are never registered under a name — the supervisor is addressed by the
pid `start_link/2,3` returns, and the elector is discovered by the member at startup
(its `$ancestors` process-dictionary entry, then `supervisor:which_children/1`) and
thereafter held as a pid. Only the **member** is locally registered, under `Name`
itself — the same atom also names its ETS table (`names_table/1`); no additional
atom is derived from it. This matters for applications that start many independent
registries dynamically (e.g. one per tenant): atoms are never garbage-collected, so
deriving additional atoms per registry (as earlier versions of this module did)
would grow the atom table without bound. See §4.8 of the design doc.

## Consistency model

All writes (`register_name`, `unregister_name`) and consistent reads
(`whereis_name_consistent`) go through the elected leader member process.
The leader is the single writer for the name table.

`whereis_name/1` (used by the OTP via-tuple machinery) is a snapshot read
served lock-free from the local member's `protected` ETS table, in the calling
process — no member-mailbox hop, no network hop, no backend round-trip. The
table is kept in sync by one-way replication casts from the leader. There is
therefore a short window after registration where a remote node's
`whereis_name/1` may still return `undefined`; this is the same
eventual-consistency trade-off as `gproc` global mode.

## Leadership

The elected leader is the member process on the Erlang node that most
recently committed a backend transaction for the elector queue — i.e.,
whoever wins the backend consensus. When leadership changes, the new leader
gathers the freshest names map from every reachable member and broadcasts a
snapshot to all followers on assumption. No distributed lock is used: the
leader-key commit fences the old leader, making the handoff window naturally
quiescent (§5.7 of the design doc).

## Auto-unregistration

The leader monitors every registered Pid. When a monitored process exits,
the leader removes the entry and propagates `{name_unregistered}` to all
follower members.

## Metadata and queries

A registration can carry metadata for its lifetime: `register_name/3` /
`set_metadata/2` attach an `index` map (queryable) and an opaque `data` payload;
`get_metadata/1` / `get_metadata_consistent/1` read it back (lock-free / leader-routed,
mirroring `whereis_name/1` / `whereis_name_consistent/1`). `query/2` /
`query_consistent/2` find every registration whose `index` satisfies a conjunction of
exact equalities. See §4.7 of the design doc.
""".
-endif.

